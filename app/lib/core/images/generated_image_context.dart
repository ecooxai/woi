import 'dart:io';

import 'package:flutter/foundation.dart';

import '../../platform/camera.dart' show jpegSize;
import '../media/media_context.dart';
import '../models/message.dart';
import 'image_encoding.dart';

/// A saved generated image and its JPEG representation for model context.
class GeneratedImageContext {
  GeneratedImageContext(this.message, this.image);
  final Message message;
  final ContextImage image;
}

bool isCompletedGeneratedImage(Message message) =>
    message.image != null &&
    (message.image!.generated ||
        (message.meta['type'] == 'image_generation' &&
            message.meta['status'] == 'completed'));

Future<GeneratedImageContext> generatedImageContext(Message message) async {
  final attachment = message.image!;
  final file = File(attachment.path);
  if (await file.length() > 48 * 1024 * 1024) {
    throw const FormatException(
      'Generated image is too large for image context.',
    );
  }
  final jpeg = await normalizeImageToJpeg(await file.readAsBytes());
  final dimensions = jpegSize(jpeg);
  final prompt = '${message.meta['prompt'] ?? ''}';
  final description = prompt.length > 2000
      ? '${prompt.substring(0, 2000)}…'
      : prompt;
  return GeneratedImageContext(
    message,
    ContextImage(
      bytes: jpeg,
      width: dimensions?.$1 ?? attachment.width,
      height: dimensions?.$2 ?? attachment.height,
      kind: 'generated',
      capturedAt: message.createdAt,
      note:
          'Image generated by the assistant in this conversation. '
          'source_message_id: ${message.id}. '
          'To modify this image, call generate_image with action edit and this source_message_id. '
          'This is artwork, not the current screen; never use it for pointer coordinates. '
          'Original image request: $description',
    ),
  );
}

/// Restore a bounded set of recent generated images for a new session. A
/// missing/corrupt historical image must not prevent the voice session opening.
Future<List<GeneratedImageContext>> recentGeneratedImageContext(
  Conversation conversation, {
  int limit = 3,
}) async {
  final messages = conversation.messages
      .where((m) => !m.compacted && isCompletedGeneratedImage(m))
      .toList();
  final recent = messages.skip(
    messages.length > limit ? messages.length - limit : 0,
  );
  final images = <GeneratedImageContext>[];
  for (final message in recent) {
    try {
      images.add(await generatedImageContext(message));
    } catch (e) {
      debugPrint('Generated image context ${message.id} unavailable: $e');
    }
  }
  return images;
}
