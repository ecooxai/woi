import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'exec_util.dart';

/// System-wide acoustic echo cancellation on PipeWire, owned by the app.
///
/// While Woi's microphone is open it hosts `libpipewire-module-echo-cancel`
/// (WebRTC AEC) in a private `pipewire -c <conf>` child process. In
/// `monitor.mode` the canceller's reference is the monitor of the *default
/// sink*, so everything the speakers play (Woi's voice, music, videos, other
/// apps) is removed from the mic, not only Woi's own playback. The mic side
/// follows the default source. Both streams are plain autoconnect streams, so
/// WirePlumber moves them when the user switches the default sink or source.
///
/// The canceller's source node is created with the lowest session priority and
/// is only ever used through an explicit capture target (pw-record or WebRTC), so it never
/// becomes (and never changes) the user's default devices; [acquire] checks
/// the defaults before and after and puts them back if anything moved.
///
/// Lifetime: the host only runs while a mic is open (plus [linger]), because
/// its mic stream shares a driver group with the sink monitor and would keep
/// the microphone running whenever anything plays. It dies with the app even
/// on SIGKILL: a tiny `sh` watchdog kills it when its stdin pipe (held only by
/// Woi) reaches EOF.
class PipewireEchoCancel {
  PipewireEchoCancel({
    this.linger = const Duration(seconds: 2),
    this.readyTimeout = const Duration(seconds: 3),
    String? instanceId,
    this.log = _defaultLog,
    this.startHostProcess,
    this.probeNode,
    this.readDefaults,
    String? micTarget,
    String? speakerTarget,
  }) : id = instanceId ?? '$pid',
       micTarget = micTarget ?? audioTarget('WOI_AUDIO_SOURCE'),
       speakerTarget = speakerTarget ?? audioTarget('WOI_AUDIO_SINK');

  /// Node names from the environment that pin Woi's audio to given devices
  /// instead of the defaults (QA on virtual devices); null when unset.
  static String? audioTarget(String variable) {
    final v = Platform.environment[variable]?.trim();
    return v == null || v.isEmpty ? null : v;
  }

  /// Mic and speaker nodes the canceller is pinned to (null: the defaults).
  final String? micTarget;
  final String? speakerTarget;

  /// How long the host keeps running after the last mic closed (mic toggles
  /// and reconnects then reuse the converged canceller).
  final Duration linger;
  final Duration readyTimeout;
  final String id;
  final void Function(String) log;

  /// Injectable OS boundaries for deterministic start/stop race coverage.
  final Future<Process> Function(String configPath)? startHostProcess;
  final Future<bool> Function(String nodeName)? probeNode;
  final Future<(String?, String?)> Function()? readDefaults;

  static void _defaultLog(String m) => stderr.writeln('woi aec: $m');

  /// Node name of the echo-cancelled source (the `pw-record --target`).
  String get sourceName => 'woi_aec_source_$_instance';
  String get _instance => _epoch == 0 ? id : '${id}_$_epoch';
  String get sourceDescription => 'Woi echo-cancelled mic ($_instance)';
  String get captureName => 'woi_aec_capture_$_instance';
  String get monitorName => 'woi_aec_reference_$_instance';

  Process? _proc;
  Future<String?>? _starting;
  File? _confFile;
  Future<void>? _stopping;
  int _epoch = 0;
  bool _hasStarted = false;
  int _users = 0;
  Timer? _lingerTimer;
  String _status = 'off';
  bool _disposed = false;

  /// Human-readable state for diagnostics ("active", "unavailable: ...").
  String get status => _status;

  /// True while the canceller process is up.
  bool get running => _proc != null;

  /// The PipeWire config the host runs. Mono at the PipeWire graph rate; the
  /// capture child converts to 24 kHz s16. AGC stays off (server VAD and the
  /// level meter want a stable gain); WebRTC's high-pass filter stays on.
  /// Noise and transient suppression are off: offline (qa/aec, turns rig) they
  /// cost the user's voice 27 dB while Woi talks (double-talk near-end -26.6 dB
  /// with them, -3.9 dB without) and removed no echo (ERLE 12.7/17.9 dB at
  /// reply starts/bodies either way, same VAD false starts), which is why a
  /// short "stop" over Woi's speech was lost. The server's far_field noise
  /// reduction handles background noise.
  ///
  /// [micTarget] / [speakerTarget] pin the mic and the reference to given
  /// nodes instead of following the defaults (QA on virtual devices:
  /// `WOI_AUDIO_SOURCE` / `WOI_AUDIO_SINK`).
  static String config({
    required String sourceName,
    required String captureName,
    required String monitorName,
    String? micTarget,
    String? speakerTarget,
    String? sourceDescription,
  }) =>
      '''
# Generated by Woi (lib/platform/linux/pipewire_aec.dart). Hosted by a private
# `pipewire -c` process for the lifetime of Woi's microphone.
context.properties = {
    log.level = 2
    core.daemon = false
    core.name = woi-aec-$sourceName
}
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
context.modules = [
    { name = libpipewire-module-rt args = { } flags = [ ifexists nofail ] }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
    { name = libpipewire-module-echo-cancel
      args = {
        library.name = aec/libspa-aec-webrtc
        # NS + transient suppression off: +23 dB of near-end in double talk, same ERLE.
        aec.args = {
            webrtc.gain_control = false
            webrtc.noise_suppression = false
            webrtc.transient_suppression = false
        }
        # Reference = monitor of the default sink: cancels ALL system audio.
        monitor.mode = true
        audio.channels = 1
        audio.position = [ MONO ]
        capture.props = {
            node.name = "$captureName"
            node.description = "Woi echo cancel (mic)"
            node.passive = true${micTarget == null ? '' : '\n            target.object = "$micTarget"'}
        }
        source.props = {
            node.name = "$sourceName"
            node.description = ${jsonEncode(sourceDescription ?? "Woi echo-cancelled mic")}
            # Never a default-device candidate.
            priority.session = 0
            priority.driver = 0
            device.intended-roles = "Communication"
        }
        # In monitor.mode the sink-monitor capture stream takes sink.props.
        sink.props = {
            node.name = "$monitorName"
            node.description = "Woi echo cancel (speaker reference)"
            node.passive = true${speakerTarget == null ? '' : '\n            target.object = "$speakerTarget"'}
        }
      }
    }
]
''';

  /// Shell watchdog: runs pipewire, kills it when stdin hits EOF (Woi died)
  /// or on SIGTERM, and exits when pipewire exits.
  static const _watchdog = r'''
exec 3<&0
pipewire -c "$1" </dev/null &
p=$!
trap 'kill $p 2>/dev/null' TERM INT HUP
{ read -r _ <&3; kill $p 2>/dev/null; } &
r=$!
wait $p
s=$?
kill $r 2>/dev/null
exit $s
''';

  /// Returns a ready, owned source. Starts and stops are serialized: a new
  /// reconnect never mistakes the old host's disappearing node for its own.
  Future<String?> acquire() async {
    if (_disposed) return null;
    _lingerTimer?.cancel();
    _lingerTimer = null;
    final stopping = _stopping;
    if (stopping != null) await stopping;
    if (_disposed) return null;
    // Recheck after waiting: another release may have armed the linger timer.
    _lingerTimer?.cancel();
    _lingerTimer = null;
    // Reserve the user before probing/startup. Otherwise the previous user
    // could release during this await and arm a stop that kills this capture.
    _users++;
    var acquired = false;
    try {
      final name = await (_starting ??= _ensureStarted());
      if (name == null || _disposed) return null;
      acquired = true;
      return name;
    } finally {
      if (!acquired) release();
    }
  }

  Future<String?> _ensureStarted() async {
    try {
      if (_proc != null && await _nodeExists(sourceName)) return sourceName;
      // A PipeWire restart may have removed the node while the watchdog is
      // still alive. Do not hand a stale source to a reconnecting recorder.
      if (_proc != null || _confFile != null) await _stopHost();
      return await _start();
    } finally {
      // _ensureStarted always awaits before this point, so the shared future
      // has already been installed by acquire().
      _starting = null;
    }
  }

  void release() {
    if (_users > 0) _users--;
    if (_users > 0 || _proc == null || _disposed) return;
    _lingerTimer?.cancel();
    _lingerTimer = Timer(linger, () {
      _lingerTimer = null;
      if (_users == 0) unawaited(stop());
    });
  }

  Future<String?> _start() async {
    if (_disposed) return null;
    final pw = which('pipewire');
    final sh = which('sh');
    if (startHostProcess == null && (pw == null || sh == null)) {
      _status = 'unavailable: pipewire not installed';
      return null;
    }
    if (_hasStarted) _epoch++;
    _hasStarted = true;
    final source = sourceName;
    final before = await (readDefaults?.call() ?? _defaults());
    if (_disposed) return null;
    final dir = await Directory.systemTemp.createTemp('woi-aec-');
    final conf = File('${dir.path}/echo-cancel.conf');
    await conf.writeAsString(
      config(
        sourceName: source,
        captureName: captureName,
        monitorName: monitorName,
        micTarget: micTarget,
        speakerTarget: speakerTarget,
        sourceDescription: sourceDescription,
      ),
    );
    final Process proc;
    try {
      proc =
          await (startHostProcess?.call(conf.path) ??
              Process.start(sh!, ['-c', _watchdog, 'woi-aec', conf.path]));
    } catch (e) {
      _status = 'unavailable: $e';
      await _deleteConf(conf);
      return null;
    }
    final errLines = <String>[];
    unawaited(proc.stdout.drain<void>());
    proc.stderr.transform(utf8.decoder).transform(const LineSplitter()).listen((
      l,
    ) {
      if (errLines.length < 20) errLines.add(l);
    });
    var exited = false;
    unawaited(
      proc.exitCode.then((code) {
        exited = true;
        if (identical(_proc, proc)) {
          _proc = null;
          _status = 'stopped (exit $code); awaiting capture recovery';
          log('echo-cancel host exited ($code)');
        }
      }),
    );
    final deadline = DateTime.now().add(readyTimeout);
    var ready = false;
    while (!exited && !_disposed && DateTime.now().isBefore(deadline)) {
      // The source has a unique generation name. Old nodes cannot satisfy
      // readiness after linger shutdown or an audio-server reconnect.
      if (await _nodeExists(source)) {
        ready = true;
        break;
      }
      await Future<void>.delayed(const Duration(milliseconds: 50));
    }
    if (!ready || exited || _disposed) {
      await _terminate(proc);
      final why = errLines.isEmpty
          ? (exited ? 'host exited' : 'timeout')
          : errLines.join(' | ');
      _status = 'unavailable: $why';
      log('system echo cancellation unavailable: $why');
      await _deleteConf(conf);
      return null;
    }
    _proc = proc;
    _confFile = conf;
    _status =
        'active (WebRTC AEC, reference: ${speakerTarget ?? 'default sink'} monitor)';
    await _restoreDefaults(before);
    return source;
  }

  /// A stop is a barrier for all following acquires. In-flight startup is
  /// joined before shutdown, and each host cleans only its own config file.
  Future<void> stop() {
    _lingerTimer?.cancel();
    _lingerTimer = null;
    return _stopping ??= _doStop();
  }

  Future<void> _doStop() async {
    try {
      final starting = _starting;
      if (starting != null) await starting;
      await _stopHost();
      _status = 'off';
    } finally {
      _stopping = null;
    }
  }

  Future<void> _stopHost() async {
    final proc = _proc;
    final conf = _confFile;
    _proc = null;
    _confFile = null;
    if (proc != null) await _terminate(proc);
    if (conf != null) await _deleteConf(conf);
  }

  static Future<void> _terminate(Process proc) async {
    // EOF is the watchdog's lifetime signal, including when startup fails.
    try {
      await proc.stdin.close();
    } catch (_) {}
    proc.kill(ProcessSignal.sigterm);
    await proc.exitCode.timeout(
      const Duration(seconds: 2),
      onTimeout: () {
        proc.kill(ProcessSignal.sigkill);
        return -9;
      },
    );
  }

  Future<void> dispose() async {
    _disposed = true;
    _users = 0;
    await stop();
  }

  static Future<void> _deleteConf(File conf) async {
    try {
      await conf.parent.delete(recursive: true);
    } catch (_) {}
  }

  Future<bool> _nodeExists(String name) async {
    if (probeNode != null) return probeNode!(name);
    final cli = which('pw-cli');
    if (cli == null) return false;
    try {
      final r = await _query(cli, ['ls', 'Node'], const Duration(seconds: 1));
      return r.exitCode == 0 && '${r.stdout}'.contains('node.name = "$name"');
    } catch (_) {
      return false;
    }
  }

  // A disconnected audio server can leave its clients waiting indefinitely.
  // Kill timed-out query processes, rather than just abandoning their futures.
  static Future<ProcessResult> _query(
    String exe,
    List<String> args,
    Duration timeout,
  ) async {
    final process = await Process.start(exe, args);
    final output = process.stdout
        .transform(const Utf8Decoder(allowMalformed: true))
        .join();
    final errors = process.stderr
        .transform(const Utf8Decoder(allowMalformed: true))
        .join();
    await process.stdin.close();
    try {
      final code = await process.exitCode.timeout(timeout);
      return ProcessResult(process.pid, code, await output, await errors);
    } on TimeoutException {
      process.kill(ProcessSignal.sigkill);
      await process.exitCode.timeout(
        const Duration(seconds: 1),
        onTimeout: () => -9,
      );
      rethrow;
    }
  }

  static Future<(String?, String?)> _defaults() async {
    final pactl = which('pactl');
    if (pactl == null) return (null, null);
    Future<String?> get(String what) async {
      try {
        final r = await _query(pactl, [what], const Duration(seconds: 2));
        final s = '${r.stdout}'.trim();
        return r.exitCode == 0 && s.isNotEmpty ? s : null;
      } catch (_) {
        return null;
      }
    }

    return (await get('get-default-source'), await get('get-default-sink'));
  }

  /// The canceller must never take over the defaults. If it did (a session
  /// manager policy we did not expect), put the user's devices back.
  Future<void> _restoreDefaults((String?, String?) before) async {
    if (before.$1 == null && before.$2 == null) return;
    final pactl = which('pactl');
    if (pactl == null) return;
    final after = await _defaults();
    if (before.$1 != null &&
        after.$1 != before.$1 &&
        (after.$1 ?? '').startsWith('woi_aec')) {
      log(
        'echo-cancel source became the default source; restoring ${before.$1}',
      );
      await _query(pactl, [
        'set-default-source',
        before.$1!,
      ], const Duration(seconds: 2));
    }
    if (before.$2 != null &&
        after.$2 != before.$2 &&
        (after.$2 ?? '').startsWith('woi_aec')) {
      log('default sink changed to ${after.$2}; restoring ${before.$2}');
      await _query(pactl, [
        'set-default-sink',
        before.$2!,
      ], const Duration(seconds: 2));
    }
  }
}
